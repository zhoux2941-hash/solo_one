export function buildNGramModel(n: number = 2): Map<string, Map<string, number>> {
  const ngrams = new Map<string, Map<string, number>>();
  
  for (const sentence of laoziCorpus) {
    for (let i = 0; i <= sentence.length - n; i++) {
      const prefix = sentence.slice(i, i + n - 1);
      const nextChar = sentence[i + n - 1];
      
      if (!ngrams.has(prefix)) {
        ngrams.set(prefix, new Map());
      }
      const charMap = ngrams.get(prefix)!;
      charMap.set(nextChar, (charMap.get(nextChar) || 0) + 1);
    }
  }
  
  return ngrams;
}

