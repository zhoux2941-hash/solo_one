export function getProgramHeaderFlags(flags: number): string {
  const result: string[] = [];
  if (flags & PF_FLAGS.PF_R) result.push('R');
  if (flags & PF_FLAGS.PF_W) result.push('W');
  if (flags & PF_FLAGS.PF_X) result.push('X');
  return result.join('') || '---';
}

export function getSectionFlags(flags: bigint): string {
  const result: string[] = [];
  if (flags & BigInt(SH_FLAGS.SHF_WRITE)) result.push('W');
  if (flags & BigInt(SH_FLAGS.SHF_ALLOC)) result.push('A');
  if (flags & BigInt(SH_FLAGS.SHF_EXECINSTR)) result.push('X');
  if (flags & BigInt(SH_FLAGS.SHF_MERGE)) result.push('M');
  if (flags & BigInt(SH_FLAGS.SHF_STRINGS)) result.push('S');
  if (flags & BigInt(SH_FLAGS.SHF_TLS)) result.push('T');
  return result.join('');
}
