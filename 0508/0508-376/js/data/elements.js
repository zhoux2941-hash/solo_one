export function getElementInfo(symbol) {
    return elements[symbol] || null;
}

export function searchElements(query) {
    const results = [];
    const lowerQuery = query.toLowerCase();
    
    for (const [symbol, info] of Object.entries(elements)) {
        if (symbol.toLowerCase().includes(lowerQuery) || 
            info.name.includes(query)) {
            results.push({ symbol, ...info });
        }
    }
    
    return results;
}

export function getPeriodicTable() {
    const table = [];
    const order = Object.keys(elements).sort((a, b) => elements[a].atomicNumber - elements[b].atomicNumber);
    
    for (const symbol of order) {
        table.push({ symbol, ...elements[symbol] });
    }
    
    return table;
}