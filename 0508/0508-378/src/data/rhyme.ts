export const getRhymingWords = (targetWord: string): string[] => {
  for (const group of Object.values(rhymeGroups)) {
    if (group.words.includes(targetWord)) {
      return group.words.filter(w => w !== targetWord);
    }
  }
  return [];
};

export const getRhymeGroup = (groupKey: string): RhymeGroup | null => {
  return rhymeGroups[groupKey] || null;
};

export const findRhymeGroupByWord = (word: string): RhymeGroup | null => {
  for (const group of Object.values(rhymeGroups)) {
    if (group.words.includes(word)) {
      return group;
    }
  }
  return null;
};

export const getAllRhymeGroups = (): RhymeGroup[] => {
  return Object.values(rhymeGroups);
};

export const recommendRhymeGroup = (chars: string[]): RhymeGroup | null => {
  const groupCounts: Record<string, number> = {};
  
  for (const char of chars) {
    for (const [key, group] of Object.entries(rhymeGroups)) {
      if (group.words.includes(char)) {
        groupCounts[key] = (groupCounts[key] || 0) + 1;
      }
    }
  }
  
  let maxCount = 0;
  let bestGroup: string | null = null;
  
  for (const [key, count] of Object.entries(groupCounts)) {
    if (count > maxCount) {
      maxCount = count;
      bestGroup = key;
    }
  }
  
  if (bestGroup) {
    return rhymeGroups[bestGroup];
  }
  
  return rhymeGroups["一东"] || null;
};

export default rhymeGroups;
