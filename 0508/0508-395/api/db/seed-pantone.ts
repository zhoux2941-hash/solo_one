function generateColorVariation(base: RGB, variationIndex: number, totalVariations: number): RGB {
  const angle = (variationIndex / totalVariations) * Math.PI * 2;
  const lightnessVariation = Math.sin(angle) * 60;
  const saturationVariation = Math.cos(angle * 1.5) * 40;

  const hsl = colorAlgorithms.rgbToHsl(base);
  
  let newL = hsl.l + lightnessVariation;
  let newS = hsl.s + saturationVariation;
  
  newL = Math.max(10, Math.min(95, newL));
  newS = Math.max(10, Math.min(100, newS));

  const newH = (hsl.h + (variationIndex * 3) % 30 + 360) % 360;

  return colorAlgorithms.hslToRgb({ h: newH, s: newS, l: newL });
}

